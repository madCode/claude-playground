package com.app.carry

import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * Carry's end of the contract, checked against a file the RUNNER actually
 * wrote rather than one this repository made up.
 *
 * Every other test here builds its own JSON, so both sides of a field name
 * are written by the same hand and agree by construction. That is how the
 * runner wrote `<date>-<class>.json` while this app looked for
 * `session-<date>-<class>.json` with 151 tests green on both sides, and how
 * `Folder.list()` came back read in the wrong order. A fixture generated by
 * `session_file.build()` is the cheapest thing that can catch a renamed or
 * misspelled key before it reaches a phone.
 *
 * Regenerate with gym-coach's `session_file.build()` on an INVENTED sheet
 * and an EMPTY history: real sheet text belongs to r/orangetheory and a
 * suggestion drawn from real history embeds the owner's weights, and this
 * repository is public (CLAUDE.md, "Privacy").
 */
class RunnerContractTest {

    private val raw = checkNotNull(javaClass.classLoader!!.getResourceAsStream("runner-session.json"))
        .bufferedReader().readText()

    @Test
    fun `a file the runner wrote decodes, with the prescription attached`() {
        val session = Session.json.decodeFromString(Session.serializer(), raw)
        assertEquals("2026-10-17", session.date)
        assertEquals("2G", session.classTag)

        val byName = session.sets.associateBy { it.displayName }
        // A plain count.
        assertEquals("8 x", byName.getValue("bench press").prescription)
        // An alternating line: the board says 10 total, the runner's math
        // number is 5, and what a person reads is the board's.
        val lunge = byName.getValue("reverse lunge")
        assertEquals("10 total x", lunge.prescription)
        assertEquals(5, lunge.prescribedReps)
        // A range, which used to be published as its floor.
        assertEquals("6-10 x", byName.getValue("deadlift").prescription)
        // A timed hold: no rep count anywhere, and the duration is the ask.
        val plank = byName.getValue("plank")
        assertEquals("45 sec of", plank.prescription)
        assertNull(plank.prescribedReps)
        assertEquals(45, plank.prescribedDurationSec)
    }

    @Test
    fun `the keys this app reads are the keys the runner writes`() {
        // Named one by one. A `@SerialName` typo decodes as null and every
        // assertion about behaviour still passes -- the field just quietly
        // never arrives, which is exactly what shipped last time.
        for (key in listOf("sheet_id", "date", "class", "borrowed_from", "sets",
                           "ref", "canonical", "components", "variant",
                           "prescribed_reps", "prescribed_text", "prescribed_duration_sec",
                           "family", "suggested", "suggested_weight", "previous_weight",
                           "streak_done", "streak_needed")) {
            assertTrue("the runner stopped writing `$key`", raw.contains("\"$key\""))
        }
        val session = Session.json.decodeFromString(Session.serializer(), raw)
        assertTrue(session.sets.isNotEmpty())
        session.sets.forEach { assertNotNull("every row needs its identity", it.key) }
    }

    @Test
    fun `the post built from a runner file carries the board's own counts`() {
        val session = Session.json.decodeFromString(Session.serializer(), raw)
        val answered = session.sets.associate { it.ref to SessionPatch.Entry(weight = 30.0) }
        val post = checkNotNull(IntelPost.compose(session, answered, emptyList()))
        assertTrue(post.text, post.text.contains("- 10 total x reverse lunge"))
        assertTrue(post.text, post.text.contains("- 6-10 x deadlift"))
        assertTrue(post.text, post.text.contains("- 45 sec of plank"))
        // The runner's math numbers must not be what goes out.
        assertTrue("5 a side is the math, not the board", !post.text.contains("- 5 x"))
        assertEquals(emptySet<String>(), post.suspect)
    }
}
